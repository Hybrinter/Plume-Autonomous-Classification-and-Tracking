"""Dataset figure/preview orchestration over already-frozen measurements.

Scientific values are never re-measured here. Preview bytes retain exact
canonical source arrays; figure coordinates are derived once, persisted, and
rendered from the same record objects. One exclusive publisher writes the
summary, numerical evidence, capture caches and all indexed render artifacts.

Satisfies: REQ-AIML-HIGH-004.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path

from flight.libs.types import Err, Ok, Result

from tools.ml_models.analysis.artifacts import BundleFile, artifact_ref
from tools.ml_models.analysis.config import DatasetAnalysisConfig, render_digest
from tools.ml_models.analysis.contracts import ArtifactKind, ArtifactRef, AvailabilityRecord
from tools.ml_models.analysis.dataset import DatasetMeasurement, dataset_summary
from tools.ml_models.analysis.dataset_artifacts import code_identity, publish_dataset_measurement
from tools.ml_models.analysis.dataset_figures import dataset_figure_data
from tools.ml_models.analysis.dataset_previews import capture_dataset_previews
from tools.ml_models.analysis.plots.dataset import render_dataset_figures
from tools.ml_models.analysis.visuals.dataset import render_dataset_visuals


def _json_file(path: str, values: object) -> BundleFile:
    """Encode finite canonical JSON without creating an output directory."""
    return BundleFile(
        path,
        json.dumps(
            values,
            sort_keys=True,
            allow_nan=False,
            separators=(",", ":"),
        ).encode("utf-8"),
    )


def _refs(
    files: tuple[BundleFile, ...],
    kind: ArtifactKind,
    population: str,
) -> Result[tuple[ArtifactRef, ...], str]:
    """Bind generated bytes to explicit kinds/populations, without re-opening source files."""
    refs: list[ArtifactRef] = []
    for file in files:
        ref = artifact_ref(
            file.path,
            file.data,
            kind=kind,
            format=file.path.rsplit(".", 1)[-1],
            population=population,
        )
        if isinstance(ref, Err):
            return ref
        refs.append(ref.value)
    return Ok(tuple(refs))


def publish_rendered_dataset(
    measured: DatasetMeasurement,
    cfg: DatasetAnalysisConfig,
) -> Result[Path, str]:
    """Capture, render and exclusively publish one comprehensive dataset-analysis bundle.

    Required rendering failures abort before reservation. Missing metadata or
    budget-disabled optional galleries remain explicit and produce indexed
    placeholders. Plot style gets its own identity tied to the frozen
    measurement identity; it does not change the underlying metric values.
    """
    try:
        captured = capture_dataset_previews(Path(cfg.dataset), measured, cfg.capture)
        if isinstance(captured, Err):
            return captured
        preview = captured.value
        recipes = dataset_figure_data(measured)
        figures = render_dataset_figures(recipes, cfg.plot)
        if isinstance(figures, Err):
            return figures
        visuals = render_dataset_visuals(preview, cfg.plot)
        if isinstance(visuals, Err):
            return visuals
        code = code_identity()
        identity = dataset_summary(measured, cfg, code, ()).measurement_id
        metadata = (
            _json_file(
                "figure-data.json",
                {
                    "dataset": asdict(measured.identity),
                    "method": "exact_frozen_dataset_figure_coordinates_v1",
                    "figures": [asdict(recipe) for recipe in recipes],
                },
            ),
            _json_file(
                "preview-manifest.json",
                {
                    "dataset": asdict(measured.identity),
                    "method": preview.method,
                    "plan": asdict(preview.plan),
                    "previews": [asdict(record) for record in preview.previews],
                },
            ),
            _json_file(
                "rendering.json",
                {
                    "measurement_id": identity,
                    "render_id": render_digest(identity, cfg.plot),
                    "plot": asdict(cfg.plot),
                    "method": "dataset_render_v1",
                },
            ),
        )
        files: list[BundleFile] = []
        refs: list[ArtifactRef] = []
        batches: tuple[tuple[tuple[BundleFile, ...], ArtifactKind, str], ...] = (
            (preview.files, "REFERENCE", "bounded exact canonical dataset previews"),
            (figures.value.files, "FIGURE", "frozen dataset figure evidence"),
            (visuals.value.files, "VISUAL", "deterministic bounded dataset gallery selections"),
            (metadata, "REFERENCE", "dataset render and capture provenance"),
        )
        for batch, kind, population in batches:
            bound = _refs(batch, kind, population)
            if isinstance(bound, Err):
                return bound
            files.extend(batch)
            refs.extend(bound.value)
        outputs = (
            (
                AvailabilityRecord(name="figures", status="AVAILABLE", required=True),
                AvailabilityRecord(
                    name="visuals",
                    status="AVAILABLE" if preview.plan.galleries else "SKIPPED",
                    reason=None
                    if preview.plan.galleries
                    else "No complete optional gallery fit the configured preview budget",
                ),
            )
            + figures.value.outputs
            + visuals.value.outputs
        )
        return publish_dataset_measurement(
            measured,
            cfg,
            extra_files=tuple(files),
            extra_refs=tuple(refs),
            extra_outputs=outputs,
            code=code,
        )
    except (OSError, TypeError, ValueError, RuntimeError, OverflowError) as exc:
        return Err(f"dataset rendering failed before publication: {exc}")
